-- Fide v2 · 3/5 — End-to-end encrypted documents (payslips, CU).
--
-- Format fide-doc-v1, produced in HR's browser (the server never sees plaintext):
--   ciphertext  = XChaCha20-Poly1305(pdf, key = file_key, nonce, ad = "fide-doc-v1|<document_id>|<member_id>")
--   wrapped_key = crypto_box_seal(file_key, employee X25519 public key)   -- 32 + 48 = 80 bytes
-- The ciphertext goes to Storage at {company_id}/{member_id}/{document_id}.bin.
--
-- Flow: create_payroll_batch() → HR uploads each object → publish_payroll_batch()
-- checks every object exists with the declared size → employees download through
-- the document-url Edge Function (signed URL + `downloaded` event).

create type public.document_kind as enum ('cedolino', 'cu', 'other');
create type public.document_status as enum ('draft', 'published', 'superseded', 'deleted');
create type public.document_event as enum ('published', 'downloaded', 'opened', 'superseded', 'deleted');
create type public.batch_status as enum ('draft', 'published');

create table public.payroll_batches (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies (id) on delete cascade,
  kind public.document_kind not null default 'cedolino',
  period date not null check (extract(day from period) = 1),
  title text not null check (char_length(title) between 1 and 120),
  status public.batch_status not null default 'draft',
  created_by uuid references public.members (id),
  created_at timestamptz not null default now(),
  published_at timestamptz,
  unique (company_id, id)
);

create table public.documents (
  -- Generated by the portal before encryption: it is bound into the AEAD data.
  id uuid primary key,
  company_id uuid not null,
  member_id uuid not null,
  batch_id uuid,
  kind public.document_kind not null,
  title text not null check (char_length(title) between 1 and 120),
  period date,
  device_key_id uuid not null,
  storage_path text not null unique,
  format text not null default 'fide-doc-v1' check (format = 'fide-doc-v1'),
  nonce text not null check (public.b64_len(nonce) = 24),
  ciphertext_sha256 text not null check (ciphertext_sha256 ~ '^[0-9a-f]{64}$'),
  size_bytes integer not null check (size_bytes between 17 and 26214400),
  status public.document_status not null default 'draft',
  supersedes_id uuid references public.documents (id),
  created_by uuid references public.members (id),
  created_at timestamptz not null default now(),
  published_at timestamptz,
  first_opened_at timestamptz,
  foreign key (company_id, member_id) references public.members (company_id, id),
  foreign key (company_id, batch_id) references public.payroll_batches (company_id, id),
  foreign key (member_id, device_key_id) references public.device_keys (member_id, id),
  check (storage_path = company_id::text || '/' || member_id::text || '/' || id::text || '.bin')
);

create index documents_member on public.documents (member_id, created_at desc);
create index documents_batch on public.documents (batch_id);

create table public.document_key_wraps (
  document_id uuid not null references public.documents (id) on delete cascade,
  device_key_id uuid not null references public.device_keys (id),
  wrapped_key text not null check (public.b64_len(wrapped_key) = 80),
  created_at timestamptz not null default now(),
  primary key (document_id, device_key_id)
);

-- Proof of delivery (L. 4/1953 electronic payslip delivery): append-only.
create table public.document_access_events (
  id bigint generated always as identity primary key,
  company_id uuid not null,
  document_id uuid not null references public.documents (id),
  member_id uuid not null,
  actor_member_id uuid references public.members (id),
  event public.document_event not null,
  created_at timestamptz not null default now(),
  foreign key (company_id, member_id) references public.members (company_id, id)
);

create index document_access_events_document on public.document_access_events (document_id, created_at);
create index document_access_events_company on public.document_access_events (company_id, created_at desc);

create trigger document_access_events_append_only before update or delete on public.document_access_events
  for each row execute function private.forbid_mutation();

-- ---------------------------------------------------------------------------
-- Storage: ciphertext only, upload-once, no client reads
