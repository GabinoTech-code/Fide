-- p_items: [{document_id, member_id, device_key_id, nonce, ciphertext_sha256,
--            size_bytes, wrapped_key, title?, supersedes_id?}]
create function public.create_payroll_batch(
  p_company_id uuid,
  p_kind public.document_kind,
  p_period date,
  p_title text,
  p_items jsonb
)
returns uuid
language plpgsql security definer
set search_path = ''
as $$
declare
  me public.members := private.require_member(p_company_id, '{hr_admin,company_owner}');
  v_batch uuid;
  item jsonb;
  v_doc uuid;
  v_member uuid;
  v_key uuid;
  v_supersedes uuid;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 2000 then
    raise exception 'invalid_items' using errcode = '22023';
  end if;

  insert into public.payroll_batches (company_id, kind, period, title, created_by)
  values (p_company_id, p_kind, date_trunc('month', p_period)::date, trim(p_title), me.id)
  returning id into v_batch;

  for item in select * from jsonb_array_elements(p_items) loop
    v_doc := (item ->> 'document_id')::uuid;
    v_member := (item ->> 'member_id')::uuid;
    v_key := (item ->> 'device_key_id')::uuid;
    v_supersedes := (item ->> 'supersedes_id')::uuid;

    if not exists (
      select 1 from public.device_keys k
      join public.members m on m.id = k.member_id
      where k.id = v_key and k.member_id = v_member and k.company_id = p_company_id
        and k.status = 'active' and m.status = 'active'
    ) then
      raise exception 'device_key_not_active' using errcode = 'P0001', detail = v_member::text;
    end if;

    if v_supersedes is not null and not exists (
      select 1 from public.documents
      where id = v_supersedes and member_id = v_member and company_id = p_company_id
        and status = 'published'
    ) then
      raise exception 'supersedes_invalid' using errcode = 'P0001', detail = v_supersedes::text;
    end if;

    insert into public.documents (
      id, company_id, member_id, batch_id, kind, title, period, device_key_id, storage_path,
      nonce, ciphertext_sha256, size_bytes, supersedes_id, created_by)
    values (
      v_doc, p_company_id, v_member, v_batch, p_kind,
      coalesce(nullif(trim(item ->> 'title'), ''), trim(p_title)),
      date_trunc('month', p_period)::date, v_key,
      p_company_id::text || '/' || v_member::text || '/' || v_doc::text || '.bin',
      item ->> 'nonce', item ->> 'ciphertext_sha256', (item ->> 'size_bytes')::int,
      v_supersedes, me.id);

    insert into public.document_key_wraps (document_id, device_key_id, wrapped_key)
    values (v_doc, v_key, item ->> 'wrapped_key');
  end loop;

  return v_batch;
end;
$$;

create function public.publish_payroll_batch(p_batch_id uuid)
returns integer
language plpgsql security definer
set search_path = ''
as $$
declare
  b public.payroll_batches;
  me public.members;
  v_missing int;
  v_count int;
begin
  select * into b from public.payroll_batches where id = p_batch_id for update;
  if not found then
    raise exception 'not_found' using errcode = 'P0002';
  end if;
  me := private.require_member(b.company_id, '{hr_admin,company_owner}');
  if b.status <> 'draft' then
    raise exception 'not_draft' using errcode = 'P0001';
  end if;

  select count(*) into v_missing
  from public.documents d
  where d.batch_id = b.id
    and not exists (
      select 1 from storage.objects o
      where o.bucket_id = 'encrypted-documents'
        and o.name = d.storage_path
        and (o.metadata ->> 'size')::bigint = d.size_bytes
    );
  if v_missing > 0 then
    raise exception 'upload_incomplete' using errcode = 'P0001', detail = v_missing::text;
  end if;

  update public.documents set status = 'superseded'
  where id in (select supersedes_id from public.documents where batch_id = b.id and supersedes_id is not null)
    and status = 'published';

  insert into public.document_access_events (company_id, document_id, member_id, actor_member_id, event)
  select d.company_id, d.supersedes_id, d.member_id, me.id, 'superseded'
  from public.documents d
  where d.batch_id = b.id and d.supersedes_id is not null;

  update public.documents set status = 'published', published_at = now()
  where batch_id = b.id;
  get diagnostics v_count = row_count;

  insert into public.document_access_events (company_id, document_id, member_id, actor_member_id, event)
  select d.company_id, d.id, d.member_id, me.id, 'published'
  from public.documents d
  where d.batch_id = b.id;

  update public.payroll_batches set status = 'published', published_at = now() where id = b.id;

  return v_count;
end;
$$;

create function public.mark_document_opened(p_document_id uuid)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  d public.documents;
begin
  update public.documents set first_opened_at = coalesce(first_opened_at, now())
  where id = p_document_id
    and member_id in (select private.my_member_ids())
    and status in ('published', 'superseded')
  returning * into d;
  if not found then
    raise exception 'not_found' using errcode = 'P0002';
  end if;

  insert into public.document_access_events (company_id, document_id, member_id, actor_member_id, event)
  values (d.company_id, d.id, d.member_id, d.member_id, 'opened');
end;
$$;

-- service_role (document-url): authorise a download for the signed-in user and
-- log it. Returns what the app needs to decrypt.
create function public.svc_document_download(p_document_id uuid, p_auth_user_id uuid)
returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  d public.documents;
  v_wrap text;
begin
  select doc.* into d
  from public.documents doc
  join public.members m on m.id = doc.member_id
  where doc.id = p_document_id
    and doc.status in ('published', 'superseded')
    and m.auth_user_id = p_auth_user_id
    and m.status = 'active';
  if not found then
    raise exception 'not_found' using errcode = 'P0002';
  end if;

  select wrapped_key into v_wrap from public.document_key_wraps
  where document_id = d.id and device_key_id = d.device_key_id;

  insert into public.document_access_events (company_id, document_id, member_id, actor_member_id, event)
  values (d.company_id, d.id, d.member_id, d.member_id, 'downloaded');

  return jsonb_build_object(
    'document_id', d.id, 'member_id', d.member_id, 'storage_path', d.storage_path,
    'format', d.format, 'nonce', d.nonce, 'wrapped_key', v_wrap,
    'device_key_id', d.device_key_id, 'ciphertext_sha256', d.ciphertext_sha256,
    'size_bytes', d.size_bytes);
end;
$$;

