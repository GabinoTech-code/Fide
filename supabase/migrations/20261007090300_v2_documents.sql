insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('encrypted-documents', 'encrypted-documents', false, 26214400, array['application/octet-stream'])
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- HR may upload exactly the objects announced by a draft document row of their
-- company. No SELECT/UPDATE/DELETE policies: objects cannot be listed,
-- overwritten or removed by clients, and downloads go through signed URLs.
create policy encrypted_documents_hr_upload on storage.objects for insert to authenticated
  with check (
    bucket_id = 'encrypted-documents'
    and exists (
      select 1 from public.documents d
      where d.storage_path = name
        and d.status = 'draft'
        and d.company_id in (select private.my_hr_company_ids())
    )
  );

