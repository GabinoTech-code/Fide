alter table public.payroll_batches enable row level security;
alter table public.documents enable row level security;
alter table public.document_key_wraps enable row level security;
alter table public.document_access_events enable row level security;

create policy payroll_batches_select on public.payroll_batches for select to authenticated
  using (company_id in (select private.my_hr_company_ids()));

create policy documents_select on public.documents for select to authenticated
  using (
    (member_id in (select private.my_member_ids()) and status in ('published', 'superseded'))
    or company_id in (select private.my_hr_company_ids())
  );

create policy document_key_wraps_select on public.document_key_wraps for select to authenticated
  using (
    exists (
      select 1 from public.documents d
      where d.id = document_id
        and d.member_id in (select private.my_member_ids())
        and d.status in ('published', 'superseded')
    )
  );

create policy document_access_events_select on public.document_access_events for select to authenticated
  using (
    member_id in (select private.my_member_ids())
    or company_id in (select private.my_hr_company_ids())
  );

revoke all on public.payroll_batches, public.documents, public.document_key_wraps,
  public.document_access_events from anon, authenticated;
grant select on public.payroll_batches, public.documents, public.document_key_wraps,
  public.document_access_events to authenticated;
